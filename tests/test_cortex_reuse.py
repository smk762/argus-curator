"""Curator reuses argus-cortex's helpers instead of keeping its own copies (#169).

A local copy of a shared helper drifts from the suite: when cortex 0.6 stopped
trusting a same-host write by DNS name, only callers of its write-guard got the
fix. This test fails when a curator module defines, at module level, a name that
argus-cortex also defines (a function, class or constant) under any of its
modules. Import the cortex one instead.

An alias of an imported name (``TargetProfile = _CortexTargetProfile``) is a
re-export, not a copy, and passes. A real name clash that is not a copy goes in
``_ALLOWED`` with the reason.
"""

from __future__ import annotations

import ast
from collections.abc import Iterator
from pathlib import Path

import argus_cortex

SRC = Path(__file__).resolve().parent.parent / "src" / "argus_curator"
CORTEX = Path(argus_cortex.__file__).resolve().parent

# (curator module, name): why it is not a copy of the cortex definition.
_ALLOWED: dict[tuple[str, str], str] = {
    ("garments.py", "MAX_EDGE"): "the garment detector's own input size, not SingGuard's upload cap",
    ("guard.py", "ADULT_POLICY"): "built from cortex's policy_text(), named for curator's callers",
    ("guard.py", "ADULT_GRANULAR_POLICY"): "built from cortex's policy_text(), named for curator's callers",
    ("guard.py", "ADULT_CAUTIOUS_POLICY"): "built from cortex's policy_text(), named for curator's callers",
    ("guard.py", "ADULT_CINEMATIC_POLICY"): "built from cortex's policy_text(), named for curator's callers",
    ("guard_context.py", "parse_xmp"): "wraps cortex's parse_xmp into (keywords, description)",
    ("models.py", "wire_schema"): "cortex's wire_schema bound to curator's WIRE_MODELS and title",
}

# Generated by hatch-vcs in both packages.
_SKIPPED_FILES = {"_version.py"}


def _defined(path: Path) -> Iterator[tuple[str, int]]:
    """Module-level names *path* defines itself: defs, classes and assignments that aren't aliases."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
            yield node.name, node.lineno
            continue
        if isinstance(node, ast.Assign):
            targets, value = node.targets, node.value
        elif isinstance(node, ast.AnnAssign) and node.value is not None:
            targets, value = [node.target], node.value
        else:
            continue
        if isinstance(value, ast.Name | ast.Attribute):  # an alias: a re-export, not a copy
            continue
        for target in targets:
            if isinstance(target, ast.Name) and not target.id.startswith("__"):
                yield target.id, node.lineno


def _cortex_names() -> dict[str, str]:
    names: dict[str, str] = {}
    for path in sorted(CORTEX.rglob("*.py")):
        if path.name in _SKIPPED_FILES:
            continue
        module = ".".join(("argus_cortex", *path.relative_to(CORTEX).with_suffix("").parts))
        for name, _ in _defined(path):
            names.setdefault(name, module)
    return names


def _copies(src: Path, cortex: dict[str, str]) -> list[str]:
    found = []
    for path in sorted(src.rglob("*.py")):
        if path.name in _SKIPPED_FILES:
            continue
        rel = path.relative_to(src).as_posix()
        for name, line in _defined(path):
            if name in cortex and (rel, name) not in _ALLOWED:
                found.append(f"{rel}:{line} defines {name}; import it from {cortex[name]}")
    return found


def test_no_module_redefines_a_cortex_helper() -> None:
    copies = _copies(SRC, _cortex_names())
    assert not copies, "local copies of argus-cortex helpers:\n  " + "\n  ".join(copies)


def test_allow_list_has_no_stale_entries() -> None:
    cortex = _cortex_names()
    stale = [
        f"{rel}: {name}"
        for rel, name in _ALLOWED
        if name not in cortex or name not in {n for n, _ in _defined(SRC / rel)}
    ]
    assert not stale, "remove these _ALLOWED entries; the clash is gone:\n  " + "\n  ".join(stale)


def test_a_planted_copy_is_caught(tmp_path: Path) -> None:
    (tmp_path / "server.py").write_text(
        "from argus_cortex.server import WriteGuard as WG\n"
        "Guard = WG\n"  # alias: fine
        "def env_flag(name):\n    return False\n"
        "class WriteGuard:\n    pass\n",
        encoding="utf-8",
    )
    copies = _copies(tmp_path, _cortex_names())
    assert [c.split(" defines ")[1].split(";")[0] for c in copies] == ["env_flag", "WriteGuard"]
